def test_tarball_rebuild():
    """Test that the distribution tarball can be extracted and rebuilt."""
    tarball = 'libmini-1.0.0.tar.gz'
    extract_dir = '/tmp/tarball-test'

    # Clean and create extraction directory
    if os.path.exists(extract_dir):
        shutil.rmtree(extract_dir)
    os.makedirs(extract_dir)

    # Extract tarball
    with tarfile.open(tarball, 'r:gz') as tar:
        tar.extractall(extract_dir)

    # Find the extracted directory
    extracted_dirs = [d for d in os.listdir(extract_dir) if os.path.isdir(os.path.join(extract_dir, d))]
    assert len(extracted_dirs) > 0, "No directory found in extracted tarball"

    build_dir = os.path.join(extract_dir, extracted_dirs[0])

    # Try to build from extracted tarball
    result = subprocess.run(['./configure', '--prefix=/tmp/tarball-install'],
                          cwd=build_dir, capture_output=True, text=True)
    assert result.returncode == 0, f"Configure from tarball failed: {result.stderr}"

    result = subprocess.run(['make'], cwd=build_dir, capture_output=True, text=True)
    assert result.returncode == 0, f"Make from tarball failed: {result.stderr}"


