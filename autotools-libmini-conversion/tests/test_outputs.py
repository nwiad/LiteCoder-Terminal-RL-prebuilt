def test_library_linkable():
    """Test that the installed library can actually be linked against."""
    install_prefix = '/tmp/test-install'
    lib_dir = os.path.join(install_prefix, 'lib')
    include_dir = os.path.join(install_prefix, 'include')

    # Create a simple test program
    test_source = '/tmp/link_test.c'
    with open(test_source, 'w') as f:
        f.write('''
#include <mini.h>
#include <stdio.h>

int main(void) {
    int sum = mini_add(5, 7);
    int product = mini_multiply(3, 4);
    printf("Sum: %d, Product: %d\\n", sum, product);
    return (sum == 12 && product == 12) ? 0 : 1;
}
''')

    # Try to compile and link
    result = subprocess.run([
        'gcc', test_source,
        f'-I{include_dir}',
        f'-L{lib_dir}',
        '-lmini',
        '-o', '/tmp/link_test'
    ], capture_output=True, text=True)

    assert result.returncode == 0, f"Failed to link against installed library: {result.stderr}"

    # Run the test program
    env = os.environ.copy()
    env['LD_LIBRARY_PATH'] = lib_dir
    result = subprocess.run(['/tmp/link_test'], capture_output=True, text=True, env=env)
    assert result.returncode == 0, "Linked test program failed to execute correctly"
    assert 'Sum: 12' in result.stdout, "Test program produced incorrect output"


