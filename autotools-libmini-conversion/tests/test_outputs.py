def test_bootstrap_workflow():
    """Test that bootstrap/autogen generates configure script."""
    # Find bootstrap script
    bootstrap_script = None
    if os.path.isfile('bootstrap') and os.access('bootstrap', os.X_OK):
        bootstrap_script = './bootstrap'
    elif os.path.isfile('autogen.sh') and os.access('autogen.sh', os.X_OK):
        bootstrap_script = './autogen.sh'

    assert bootstrap_script is not None, "No executable bootstrap/autogen.sh script found"

    # Run bootstrap
    result = subprocess.run([bootstrap_script], capture_output=True, text=True)
    assert result.returncode == 0, f"Bootstrap failed: {result.stderr}"

    # Verify configure was generated
    assert os.path.isfile('configure'), "configure script not generated by bootstrap"
    assert os.access('configure', os.X_OK), "configure script is not executable"


