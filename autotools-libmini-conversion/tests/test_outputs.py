def test_pkgconfig_functionality():
    """Test that pkg-config file works for downstream compilation."""
    install_prefix = '/tmp/test-install'
    lib_dir = os.path.join(install_prefix, 'lib')
    pkgconfig_dir = os.path.join(lib_dir, 'pkgconfig')

    # Set PKG_CONFIG_PATH
    env = os.environ.copy()
    env['PKG_CONFIG_PATH'] = pkgconfig_dir

    # Test pkg-config --cflags
    result = subprocess.run(['pkg-config', '--cflags', 'libmini'],
                          capture_output=True, text=True, env=env)
    assert result.returncode == 0, "pkg-config --cflags failed"
    assert '-I' in result.stdout, "pkg-config --cflags doesn't include -I flag"

    # Test pkg-config --libs
    result = subprocess.run(['pkg-config', '--libs', 'libmini'],
                          capture_output=True, text=True, env=env)
    assert result.returncode == 0, "pkg-config --libs failed"
    assert '-lmini' in result.stdout, "pkg-config --libs doesn't include -lmini"

    # Create a test program
    test_program = '/tmp/test_downstream.c'
    with open(test_program, 'w') as f:
        f.write('''
#include <mini.h>
#include <stdio.h>

int main(void) {
    int result = mini_add(10, 20);
    printf("Result: %d\\n", result);
    return (result == 30) ? 0 : 1;
}
''')

    # Compile using pkg-config
    result = subprocess.run(
        ['sh', '-c', f'gcc {test_program} $(pkg-config --cflags --libs libmini) -o /tmp/test_downstream'],
        capture_output=True, text=True, env=env
    )
    assert result.returncode == 0, f"Compilation with pkg-config failed: {result.stderr}"

    # Run the compiled program
    result = subprocess.run(['/tmp/test_downstream'], capture_output=True, text=True, env=env)
    assert result.returncode == 0, "Test program execution failed"
    assert 'Result: 30' in result.stdout, "Test program produced incorrect output"


